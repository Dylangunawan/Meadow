/// Best-effort RGBA colour for a block path (without namespace).
pub fn guess_color(path: &str) -> [u8; 4] {
    if let Some((_, c)) = EXACT.iter().find(|(k, _)| *k == path) {
        let a = if *c == 0 && path.ends_with("air") { 0 } else { 255 };
        return rgba(*c, a);
    }
    // Strip common shape suffixes so that e.g. "oak_stairs" matches "oak".
    for (k, c) in KEYWORDS {
        if path.contains(k) {
            let a = if path.contains("glass") || path.contains("window") || *k == "water" || *k == "ice" {
                160
            } else {
                255
            };
            return rgba(*c, a);
        }
    }
    rgba(0x8a8a8a, 255)
}

fn rgba(c: u32, a: u8) -> [u8; 4] {
    [(c >> 16) as u8, (c >> 8) as u8, c as u8, a]
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn heuristics() {
        assert_eq!(guess_color("air")[3], 0);
        assert_eq!(guess_color("stone"), [0x7d, 0x7d, 0x7d, 255]);
        let oak = guess_color("oak_stairs");
        assert_eq!(oak, rgba(0xa2834f, 255));
        // A Conquest block
        let c = guess_color("blue_schist_dwarven_column_vertical_quarter");
        assert_eq!(c, rgba(0x35399d, 255));
    }
}
