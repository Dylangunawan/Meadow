#!/usr/bin/env python3
"""Generate Meadow's vanilla block/biome tables from PrismarineJS/minecraft-data.

Usage: python3 tools/gen_vanilla_data.py <path-to-minecraft-data-checkout>

minecraft-data is MIT licensed (https://github.com/PrismarineJS/minecraft-data).
The output files are committed so building Meadow needs no network access.
"""
import json
import os
import sys

# Version index -> minecraft-data folder. The index is what `since` refers to and must
# match `meadow_blocks::McVersion` ordering.
VERSIONS = [
    ("1.18.2", "1.18"),
    ("1.19.4", "1.19.4"),
    ("1.20.1", "1.20"),
    ("1.20.4", "1.20.4"),
    ("1.20.6", "1.20.5"),
    ("1.21.1", "1.21.1"),
    ("1.21.4", "1.21.4"),
    ("1.21.5", "1.21.5"),
    ("1.21.8", "1.21.8"),
    ("1.21.10", "1.21.9"),
    ("1.21.11", "1.21.11"),
    ("26.1", "26.1"),
]


def load(root, folder, kind):
    with open(os.path.join(root, "data", "pc", folder, kind + ".json")) as f:
        return json.load(f)


def prop_values(p):
    if p["type"] == "bool":
        return ["true", "false"]
    return p["values"]


def main():
    root = sys.argv[1]
    out_dir = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "data")
    present = []
    for _, folder in VERSIONS:
        present.append({b["name"] for b in load(root, folder, "blocks")})
    latest = load(root, VERSIONS[-1][1], "blocks")
    lines = ["# name\tsince\tflags\tproperties\tdefault  (generated by tools/gen_vanilla_data.py)"]
    for b in latest:
        name = b["name"]
        since = next(i for i, s in enumerate(present) if name in s)
        flags = []
        if b.get("transparent"):
            flags.append("t")
        if b.get("emitLight"):
            flags.append("l%d" % b["emitLight"])
        if b.get("boundingBox") == "empty":
            flags.append("e")
        props = []
        for p in b["states"]:
            props.append(p["name"] + ":" + ",".join(prop_values(p)))
        # Default state: first property is most significant in the state id.
        offset = b["defaultState"] - b["minStateId"]
        counts = [len(prop_values(p)) for p in b["states"]]
        idx = []
        for c in reversed(counts):
            idx.append(offset % c)
            offset //= c
        idx.reverse()
        default = ",".join(str(i) for i in idx)
        lines.append("\t".join([name, str(since), "".join(flags) or "-", ";".join(props) or "-", default or "-"]))
    with open(os.path.join(out_dir, "vanilla_blocks.tsv"), "w") as f:
        f.write("\n".join(lines) + "\n")

    biomes = load(root, VERSIONS[-1][1], "biomes")
    blines = ["# name\tdimension\tcategory\tcolor\ttemperature"]
    for b in biomes:
        blines.append("\t".join([b["name"], b.get("dimension", "overworld"), b.get("category", "none"),
                                 "%06x" % b.get("color", 0), str(b.get("temperature", 0.5))]))
    with open(os.path.join(out_dir, "vanilla_biomes.tsv"), "w") as f:
        f.write("\n".join(blines) + "\n")
    print("blocks:", len(latest), "biomes:", len(biomes))


if __name__ == "__main__":
    main()
